import assert from "node:assert/strict";
import {DEFAULT_DRINK_ROUTINE,normalizeDrinkRoutine,drinkRoutineHabits,visitExtras} from "../lib/household-routines";
const ground={...DEFAULT_DRINK_ROUTINE,coffeeFormat:"ground" as const,coffeeCupsPerDay:3,coffeeGramsPerCup:9,coffeeMilkCupsPerDay:2,cocoaCupsPerDay:1};
const habits=drinkRoutineHabits(ground);
assert.deepEqual(habits.map(x=>[x.name,x.qty,x.unit,x.days]),[["Café molido",27,"g",1],["Cacao soluble",15,"g",1],["Leche",.32,"L",1]]);
assert.deepEqual(drinkRoutineHabits({...ground,coffeeFormat:"pods",coffeeCupsPerDay:2,coffeeMilkCupsPerDay:0,cocoaCupsPerDay:0})[0].qty,2);
assert.equal(drinkRoutineHabits({...ground,coffeeFormat:"beans"})[0].name,"Café en grano");
assert.equal(drinkRoutineHabits({...ground,coffeeFormat:"instant"})[0].name,"Café soluble");
const guests=visitExtras(ground,4,true,"2026-10-14","vis-1");
assert.equal(guests.length,2);
assert.equal(guests[0].qty,36);
assert.equal(guests[1].qty,.24);
assert.equal(visitExtras(ground,0,true,"2026-10-14","vis-2").length,0);
assert.equal(visitExtras(ground,3,false,"2026-10-14","vis-3").length,1);
assert.equal(visitExtras({...ground,coffeeFormat:"none"},3,true,"2026-10-14","vis-4").length,0);
assert.equal(normalizeDrinkRoutine({...ground,coffeeMilkCupsPerDay:99}).coffeeMilkCupsPerDay,3);
assert.equal(normalizeDrinkRoutine({coffeeFormat:"pods",coffeeCupsPerDay:-5}).coffeeCupsPerDay,0);
assert.equal(drinkRoutineHabits(DEFAULT_DRINK_ROUTINE).length,0);
console.log("PASS: 12 household drink routine and visitor checks");
