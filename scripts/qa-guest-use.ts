import assert from "node:assert/strict";
import {chargeVisitorUse} from "../lib/guest-use";
import {estimateInventoryConsumption,type ConsumptionExtra} from "../lib/consumption-engine";
const today="2026-10-14";
const routine=[{id:"coffee",name:"Café molido",qty:10,unit:"g",days:1}];
const old={id:"old",name:"Café molido",category:"Despensa",qty:100,unit:"g",purchasedAt:"2026-10-10",stock:"hay"};
const newer={...old,id:"new",qty:150,purchasedAt:today};
const extra:ConsumptionExtra={id:"visitor-x",name:"Café molido",qty:30,unit:"g",date:today};
const expected=(item:typeof old,inventory:typeof old[])=>estimateInventoryConsumption(item,inventory,[],routine,[],today,[]);
const result=chargeVisitorUse([old,newer],[extra],today,item=>expected(item,[old,newer]),null);
assert.equal(result.inventory[0].qty,100,"confirmed/recorded physical quantity stays intact");
assert.equal(result.inventory[1].qty,150,"later purchase stays physically intact");
assert.equal(result.inventory[0].estimateAnchorQty,30,"visitor use reduces old predicted lot once");
assert.equal(result.inventory[1].estimateAnchorQty,undefined,"visitor use must not touch a second lot when old lot has enough");
assert.equal(result.events[0].charged,true,"event must not be charged on subsequent reads");
assert.equal(estimateInventoryConsumption(result.inventory[0],result.inventory,[],routine,[],today,result.events).estimatedQty,30,"a repeated forecast must not double subtract visitors");
const recipeCheckpoint={...result.inventory[0],qty:90,estimateAnchorQty:20,estimateAnchorDate:today};
assert.equal(estimateInventoryConsumption(recipeCheckpoint,[recipeCheckpoint,newer],[],routine,[],today,result.events).estimatedQty,20,"cooking after a visit must not subtract guest use again");
const big=chargeVisitorUse([old,newer],[{...extra,qty:80}],today,item=>expected(item,[old,newer]),null);
assert.equal(big.inventory[0].estimateAnchorQty,0);
assert.equal(big.inventory[1].estimateAnchorQty,130,"a large visitor event may span two lots without duplication");
assert.equal(estimateInventoryConsumption(big.inventory[1],big.inventory,[],routine,[],today,big.events).estimatedQty,130);
const milk={id:"milk",name:"Leche",qty:2,unit:"bricks",purchasedAt:today,stock:"hay"};
const milkExtra:ConsumptionExtra={id:"milk1",name:"Leche",qty:.24,unit:"L",date:today};
const milkCharged=chargeVisitorUse([milk],[milkExtra],today,item=>({estimatedQty:item.qty}),1);
assert.equal(milkCharged.inventory[0].estimateAnchorQty,1.76,"known 1 L carton enables measured milk use");
assert.deepEqual(milkCharged.unmatched,[]);
const milkUnknown=chargeVisitorUse([milk],[milkExtra],today,item=>({estimatedQty:item.qty}),null);
assert.equal(milkUnknown.inventory[0].estimateAnchorQty,undefined,"unknown carton must not be guessed");
assert.deepEqual(milkUnknown.unmatched,["Leche"],"unknown carton must be reported rather than guessed");
const frozen=chargeVisitorUse([{...old,location:"Congelador"}],[extra],today,item=>({estimatedQty:item.qty}),null);
assert.equal(frozen.inventory[0].estimateAnchorQty,undefined);
assert.deepEqual(frozen.unmatched,["Café molido"]);
console.log("PASS: 14 visitor charge-once checks (oldest lot, cooking, milk packs, frozen, unknown size)");
