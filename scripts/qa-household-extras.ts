import assert from "node:assert/strict";
import {estimateConsumption,estimateInventoryConsumption} from "../lib/consumption-engine";
const now="2026-10-14",old="2026-10-10";
const coffee={id:"a",name:"Café molido",category:"Despensa",qty:100,unit:"g",purchasedAt:old,stock:"hay"};
const later={...coffee,id:"b",qty:150,purchasedAt:now};
const habit=[{id:"routine-coffee",name:"Café molido",qty:10,unit:"g",days:1}];
const extras=[{id:"visitor-a",name:"Café molido",qty:30,unit:"g",date:now}];
const base=estimateConsumption(coffee,[],habit,[],now);
const special=estimateConsumption(coffee,[],habit,[],now,1,extras);
assert.equal(base.dailyRate,10);
assert.equal(special.dailyRate,10,"visitors must never become the normal daily rate");
assert.equal(base.estimatedQty,60);
assert.equal(special.estimatedQty,30);
const first=estimateInventoryConsumption(coffee,[coffee,later],[],habit,[],now,extras);
const second=estimateInventoryConsumption(later,[coffee,later],[],habit,[],now,extras);
assert.equal(first.estimatedQty,30,"charge visitor coffee once to oldest lot");
assert.equal(second.estimatedQty,150,"do not double subtract from new lot");
const bad=estimateConsumption(coffee,[],habit,[],now,1,[{...extras[0],date:"2026-10-15"}]);
assert.equal(bad.estimatedQty,base.estimatedQty,"future guest event must not change today");
const cocoa={id:"cocoa",name:"ColaCao",qty:300,unit:"g",purchasedAt:old,stock:"hay"};
const cocoaHabit=[{id:"routine-cocoa",name:"Cacao soluble",qty:15,unit:"g",days:1}];
assert.equal(estimateConsumption(cocoa,[],cocoaHabit,[],now).dailyRate,15);
const capsule={name:"Cápsulas de café",qty:20,unit:"uds",purchasedAt:old};
const capHabit=[{id:"caps",name:"Cápsulas de café",qty:2,unit:"uds",days:1}];
assert.equal(estimateConsumption(capsule,[],capHabit,[],now).estimatedQty,12);
assert.equal(estimateConsumption(coffee,[],habit,[],now,1,[{...extras[0],name:"Leche",unit:"L"}]).estimatedQty,60);
assert.equal(estimateInventoryConsumption(coffee,[coffee],[],habit,[],now).dailyRate,10);
assert.equal(estimateInventoryConsumption({...coffee,location:"Congelador"},[{...coffee,location:"Congelador"}],[],habit,[],now,extras).estimatedQty,100);
console.log("PASS: 12 exception-based forecast checks (baseline, lot accounting, formats, dates)");
