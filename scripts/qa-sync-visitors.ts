import assert from "node:assert/strict";
import {mergeHouseholdState} from "../lib/sync-merge";
const item={id:"coffee",name:"Café molido",category:"Despensa",qty:100,unit:"g",stock:"hay",purchasedAt:"2026-10-14",estimateAnchorDate:"2026-10-14",estimateAnchorQty:100};
const base={inventory:[item],shopping:[],purchaseHistory:[],stockChecks:[],profile:{consumptionHabits:[],consumptionExtras:[]},spent:0,waste:0,wasteSaved:0,purchaseSessions:[],mealHistory:[]};
const a={id:"guest-a",name:"Café molido",qty:30,unit:"g",date:"2026-10-14",charged:true};
const b={id:"guest-b",name:"Café molido",qty:20,unit:"g",date:"2026-10-14",charged:true};
const left={...base,inventory:[{...item,estimateAnchorQty:70}],profile:{...base.profile,consumptionExtras:[a]}};
const right={...base,inventory:[{...item,estimateAnchorQty:80}],profile:{...base.profile,consumptionExtras:[b]}};
const merged=mergeHouseholdState(base,left,right);
assert.equal(merged.inventory[0].qty,100,"physical quantity must remain unchanged");
assert.equal(merged.inventory[0].estimateAnchorQty,50,"two independent guest consumptions must both reduce the forecast");
assert.equal(merged.profile.consumptionExtras.length,2,"merged audit must retain both separate events");
const duplicated=mergeHouseholdState(base,left,{...right,inventory:[{...item,estimateAnchorQty:70}],profile:{...base.profile,consumptionExtras:[a]}});
assert.equal(duplicated.inventory[0].estimateAnchorQty,70,"the same event on two devices must not be double counted");
assert.equal(duplicated.profile.consumptionExtras.length,1);
const unchanged=mergeHouseholdState(base,base,right);
assert.equal(unchanged.inventory[0].estimateAnchorQty,80,"remote-only extra must be preserved");
const competingManual=mergeHouseholdState(base,{...left,inventory:[{...item,qty:75,lastStockCheckId:"manual1",estimateAnchorQty:75}]},right);
assert.equal(competingManual.inventory[0].qty,75,"explicit manual recount takes priority over an inferred projection");
console.log("PASS: 7 family concurrent-visitor merge checks (independent events, duplicate IDs, manual recount)");
